const dict: Record<Lang, Record<TKey, string>> = { en, am };

interface LangState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useLang = create<LangState>()(
  persist(
    (set) => ({
      lang: telegramLanguage === 'am' ? 'am' : 'en',
      setLang: (lang) => {
        document.documentElement.lang = lang;
        set({ lang });
      },
    }),
    { name: 'hikma-lang' },
  ),
);

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = dict[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useLang((s) => s.lang);
  const t = (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
  /** Picks the Amharic or English field of a bilingual record. */
  const pick = (enValue: string | null | undefined, amValue: string | null | undefined) =>
    (lang === 'am' ? amValue || enValue : enValue || amValue) ?? '';
  return { t, lang, pick };
}
